"""User-created reference markers in physical DICOM patient coordinates (LPS).

Important: these are manually positioned spherical reference markers, NOT
voxel-accurate tumor segmentation or clinical labels inferred by AI.
"""
import json
import math
import re
import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from . import database
from .dicom_service import find_series
from .storage import load_study, study_path

router = APIRouter()
CATEGORIES = {"lesion", "brain", "ventricles", "spinal_cord", "vessels", "brainstem", "cerebellum", "leptomeningeal", "nerves", "other"}
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


class MarkerIn(BaseModel):
    series_id: str
    category: str
    label: str = Field(min_length=1, max_length=70)
    color: str
    radius_mm: float = Field(ge=1.0, le=30.0)
    position_mm: list[float] = Field(min_length=3, max_length=3)
    source_type: str = "manual_reference"
    finding_id: str | None = None


def validate(input: MarkerIn, study: dict):
    find_series(study, input.series_id)
    if input.category not in CATEGORIES:
        raise HTTPException(400, "Categoría no válida")
    if input.source_type not in ("manual_reference", "manual_from_slice"):
        raise HTTPException(400, "Origen del marcador no permitido")
    if input.finding_id:
        if input.source_type!="manual_from_slice":
            raise HTTPException(400,"Una cita del informe debe asociarse a un punto elegido en los cortes")
        from .report_insights import info
        try:
            uuid.UUID(input.finding_id)
        except ValueError as exc:
            raise HTTPException(400,"Identificador de hallazgo inválido") from exc
        result=info(study["id"])
        match=next((f for f in result.get("findings",[]) if f["id"]==input.finding_id),None)
        if not match or match["category"]!=input.category:
            raise HTTPException(400,"La mención del informe no corresponde a esa estructura")
        if match.get("assertion")=="negated" or match.get("review_status")=="dismissed":
            raise HTTPException(400,"No se puede ubicar una mención negada o descartada")
    if input.source_type=="manual_from_slice":
        from .volume import ensure_volume
        import numpy as np
        geometry=ensure_volume(study_path(study["id"]),study,input.series_id)
        direction=np.asarray(geometry["full_direction"]).reshape(3,3)
        displacement=np.asarray(input.position_mm)-np.asarray(geometry["full_origin"])
        ijk=(direction.T @ displacement)/np.asarray(geometry["full_spacing"])
        if not all(-.6<=coord<=dim-.4 for coord,dim in zip(ijk,geometry["full_dimensions"])):
            raise HTTPException(400,"El punto seleccionado no cae dentro de la serie DICOM")

    if not HEX.fullmatch(input.color):
        raise HTTPException(400, "Color hexadecimal no válido")
    if not input.label.strip():
        raise HTTPException(400,"El marcador necesita una etiqueta")
    if not all(math.isfinite(value) and abs(value) <= 10000 for value in input.position_mm):
        raise HTTPException(400, "Coordenadas fuera de rango")
    # Enforce UUID for the source series, as generated by the DICOM inventory.
    try:
        uuid.UUID(input.series_id)
    except (ValueError, TypeError):
        raise HTTPException(400, "Identificador de serie no válido")


def marker_list(study_id: str):
    load_study(study_id)
    if database.enabled():
        with database.connect() as conn:
            rows = conn.execute(
                """SELECT id, series_id, category, label, color, radius_mm,
                          x_mm, y_mm, z_mm, created_at, source_type, finding_id, review_status
                   FROM rm_annotations WHERE study_id=%s ORDER BY created_at""",
                (study_id,),
            ).fetchall()
        return [
            {"id": str(row[0]), "series_id": str(row[1]), "category": row[2],
             "label": row[3], "color": row[4], "radius_mm": row[5],
              "position_mm": [row[6], row[7], row[8]], "created_at": row[9].isoformat(),
             "source_type":row[10], "finding_id":str(row[11]) if row[11] else None,
             "review_status":row[12]}
            for row in rows
        ]
    path = study_path(study_id) / "markers.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else []


@router.get("/api/studies/{study_id}/markers")
def get_markers(study_id: str):
    return marker_list(study_id)


@router.post("/api/studies/{study_id}/markers", status_code=201)
def add_marker(study_id: str, payload: MarkerIn):
    record = load_study(study_id)
    validate(payload, record)
    if len(marker_list(study_id)) >= 250:
        raise HTTPException(413, "Máximo 250 marcadores por estudio")
    marker = {
        "id": str(uuid.uuid4()), "series_id": payload.series_id,
        "category": payload.category, "label": payload.label.strip(),
        "color": payload.color.lower(), "radius_mm": payload.radius_mm,
        "position_mm": payload.position_mm,
        "source_type":payload.source_type, "finding_id":payload.finding_id,
        "review_status":"unverified",
        "created_at": datetime.now(timezone.utc).isoformat(),
    }
    if database.enabled():
        with database.connect() as conn:
            conn.execute(
                """INSERT INTO rm_annotations
                   (id,study_id,series_id,category,label,color,radius_mm,x_mm,y_mm,z_mm,source_type,finding_id,review_status)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                (marker["id"],study_id,marker["series_id"],marker["category"],
                 marker["label"],marker["color"],marker["radius_mm"],
                 *marker["position_mm"],marker["source_type"],
                 marker["finding_id"],marker["review_status"]),
            )
    else:
        all_markers = marker_list(study_id)
        all_markers.append(marker)
        (study_path(study_id) / "markers.json").write_text(
            json.dumps(all_markers,ensure_ascii=False),encoding="utf-8"
        )
    return marker


@router.delete("/api/studies/{study_id}/markers/{marker_id}",status_code=204)
def remove_marker(study_id: str, marker_id: str):
    from fastapi import Response
    load_study(study_id)
    try:
        uuid.UUID(marker_id)
    except ValueError:
        raise HTTPException(404,"Marcador no encontrado")
    if database.enabled():
        with database.connect() as conn:
            result=conn.execute(
                "DELETE FROM rm_annotations WHERE study_id=%s AND id=%s",
                (study_id,marker_id),
            )
            if result.rowcount==0:
                raise HTTPException(404,"Marcador no encontrado")
    else:
        markers=marker_list(study_id)
        kept=[m for m in markers if m["id"]!=marker_id]
        if len(markers)==len(kept):
            raise HTTPException(404,"Marcador no encontrado")
        (study_path(study_id) / "markers.json").write_text(
            json.dumps(kept,ensure_ascii=False),encoding="utf-8"
        )
    return Response(status_code=204)
